#!/usr/bin/env python3
"""Адресация конфигурации слоя: каталог задаётся снаружи, а не кодом.

Зачем. До этого модуля каждый читатель выводил путь к конфигурации из
собственного расположения (``Path(__file__).parent``), в том числе файлы
измерителя. Код нельзя было перенести, не сломав чтение: он искал
конфигурацию рядом с собой.

Модуль вводит одну точку разрешения. Значение по умолчанию оставляет файлы
там же, где они лежат, поэтому сам по себе он ничего не двигает: он лишь
делает расположение настраиваемым.

Запасных вариантов и пустых умолчаний нет: имя вне перечня и нечитаемый
файл дают закрытый отказ, а не тихое «ничего».
"""

from __future__ import annotations

import os
from pathlib import Path

CONFIG_ENV = "MEMORY_CONFIG_DIR"

# Перечень закрыт: адресовать через этот модуль можно только известную
# конфигурацию. Неизвестное имя - отказ, иначе модуль превратился бы в
# универсальный способ прочитать произвольный файл по внешнему пути.
CONFIG_NAMES = (
    "eval_questions.json",
    "topics.json",
)

# Исходная точка стенда живёт в каталоге конфигурации рядом с вопросами
# (решение владельца В-11 от 31.08.2026), но в CONFIG_NAMES НЕ входит, и
# это не оплошность: перечень адресует конфигурацию, которую читает код,
# а пересдача точки это штатное событие, а не правка кода.
#
# ⚠️ Прежняя редакция держала точку рядом с кодом ровно потому, что
# каталог конфигурации выбирается переменной среды, и подмена каталога
# подменила бы планку качества молча. Возражение снято не отменой, а
# следом: хеш действующей точки пишется в поколение активации, и
# расхождение живой точки с поколением видно в статусе. Молча подмена
# больше не проходит; блокировать её решено не было, потому что точка
# ездит git-ом между машинами, а поколение местное, и после законной
# пересдачи на одной машине вторая законно расходится до своей
# активации (решение владельца 31.08.2026).
BASELINE_NAME = "eval_baseline.json"


class ConfigPathError(ValueError):
    """Закрытый отказ адресации конфигурации."""


def _разрешить() -> Path:
    заданный = os.environ.get(CONFIG_ENV)
    if заданный:
        return Path(заданный).expanduser().resolve()
    return Path(__file__).resolve().parent


# Каталог разрешается ОДИН раз на процесс, при первом импорте модуля.
# Иначе одна операция могла бы прочитать конфигурацию из двух разных мест:
# файлы измерителя берут пути при загрузке модуля, а манифесты собираются
# позже. Оболочки задают переменную в прологе, то есть до любого импорта.
_DIR = _разрешить()


def config_dir() -> Path:
    """Каталог конфигурации, единый на весь процесс."""
    return _DIR


def _reset_for_tests() -> Path:
    """Перечитать переменную. Только для тестов адресации."""
    global _DIR
    _DIR = _разрешить()
    return _DIR


def config_path(name: str) -> Path:
    if name not in CONFIG_NAMES:
        raise ConfigPathError(
            f"{name}: имя вне перечня конфигурации слоя")
    return config_dir() / name


def baseline_path() -> Path:
    """Действующая исходная точка стенда. История хранится в git конфигурации."""
    return config_dir() / BASELINE_NAME

