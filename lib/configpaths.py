#!/usr/bin/env python3
"""Адресация конфигурации слоя: каталог задаётся снаружи, а не кодом.

Зачем. До этого модуля каждый читатель выводил путь к конфигурации из
собственного расположения (``Path(__file__).parent``), в том числе файлы
измерителя. Код нельзя было перенести, не сломав чтение: он искал
конфигурацию рядом с собой.

Модуль вводит одну точку разрешения. Значение по умолчанию это
``~/.agent-memory-config``, где конфигурация живёт после разделения
репозиториев; переменная нужна только для другого каталога. В каталоге
``topics.json``, ``eval_questions.json`` и исходная точка стенда
``eval_baseline.json``: она лежит рядом с вопросами, а не рядом с кодом,
чтобы код переносился без планки качества корпуса (решение В-11, 31.08.2026).

Запасных вариантов и пустых умолчаний нет: нечитаемый файл даёт закрытый
отказ, а не тихое «ничего».
"""

from __future__ import annotations

import os
from pathlib import Path

CONFIG_ENV = "MEMORY_CONFIG_DIR"


def _разрешить() -> Path:
    # Без переменной (или с пустой) каталог это ~/.agent-memory-config.
    # Прежнее умолчание «рядом с lib» пережило разделение репозиториев, но
    # topics.json там больше не лежит: каждая точка входа без переменной
    # падала, а установщик и документы обходили это своим значением.
    заданный = os.environ.get(CONFIG_ENV)
    if заданный:
        return Path(заданный).expanduser().resolve()
    return (Path.home() / ".agent-memory-config").resolve()


# Каталог разрешается ОДИН раз на процесс, при первом импорте модуля.
# Иначе одна операция могла бы прочитать конфигурацию из двух разных мест:
# файлы измерителя берут пути при загрузке модуля, а манифесты собираются
# позже. Оболочки задают переменную в прологе, то есть до любого импорта.
_DIR = _разрешить()


def config_dir() -> Path:
    """Каталог конфигурации, единый на весь процесс."""
    return _DIR


def _reset_for_tests() -> Path:
    """Перечитать переменную. Только для тестов адресации."""
    global _DIR
    _DIR = _разрешить()
    return _DIR


def config_path(name: str) -> Path:
    return config_dir() / name

